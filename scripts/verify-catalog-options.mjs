import fs from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context=vm.createContext({window:{}});
vm.runInContext(await fs.readFile(new URL('../catalog-options.js',import.meta.url),'utf8'),context);
const { normalize,add }=context.window.MagnumOptions;
const cases=[['brand',' hatsan ','HATSAN'],['brand','Rock   Island Armory','ROCK ISLAND ARMORY'],['caliber','12ga','12 GA'],['caliber','12 gauge','12 GA'],['caliber','12 GA','12 GA'],['caliber','.22lr','22 LR'],['caliber','9x19mm','9×19 MM'],['caliber','9 x 19 mm','9×19 MM'],['caliber','.308win','308 WIN'],['caliber','7,62x53R','7.62×53R'],['barrelLength','051,50 cm','51.5'],['barrelLength','50','50'],['barrelLength','130 სმ','130']];
for(const [kind,input,expected]of cases)assert.equal(normalize(kind,input),expected);
for(const input of ['9x19','9x19mm','9 mm Luger'])assert.equal(normalize('caliber',input),'9×19 MM');
for(const input of ['.410','.410 gauge','.410 bore'])assert.equal(normalize('caliber',input),'.410 BORE');
for(const [kind,input]of [['brand',''],['brand','<img>'],['caliber','gauge'],['barrelLength','0'],['barrelLength','131'],['barrelLength','51.123'],['barrelLength','20in']])assert.throws(()=>normalize(kind,input));
let inserts=0;
const db=(result)=>({from(table){assert.equal(table,'catalog_options');return{insert(row){inserts++;assert.equal(row.value,'NEW BRAND');return{async select(){return result}}}}}});
assert.equal((await add(null,'brand','hatsan',['HATSAN'])).existed,true);
assert.equal((await add(null,'caliber','12 gauge',['12 GA'])).value,'12 GA');
assert.equal(inserts,0);
assert.equal((await add(db({data:[{value:'NEW BRAND'}]}),'brand','new brand',[])).existed,false);
assert.equal((await add(db({error:{code:'23505'}}),'brand','new brand',[])).existed,true);
await assert.rejects(()=>add(db({error:{code:'42501'}}),'brand','new brand',[]));
await assert.rejects(()=>add(db({data:[]}),'brand','new brand',[]));
console.log('Catalog option checks passed: canonical spelling, validation, duplicate/race handling and failed writes.');
